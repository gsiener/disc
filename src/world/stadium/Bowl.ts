/**
 * Folding stadium seat. The silhouette that matters at 40 m is: a raked back
 * with a slot across it, a real gap between the back and the pan, and a narrow
 * pedestal so the row reads as individual seats rather than a solid bench.
 */
function buildSeatGeometry(detailed: boolean): THREE.BufferGeometry {
  const BACK: RGB = [1, 1, 1];
  const PAN: RGB = [0.95, 0.95, 0.95];
  const FRAME: RGB = [0.4, 0.4, 0.42];
  const TILT = -0.15;

  const list: Part[] = detailed
    ? [
      // back, split by a moulded slot
      { geo: UNIT_BOX, m: mat(0, 0.585, -0.135, TILT, 0, 0, 0.455, 0.20, 0.055), color: BACK, uvScale: 0.9 },
      { geo: UNIT_BOX, m: mat(0, 0.815, -0.170, TILT, 0, 0, 0.455, 0.21, 0.055), color: BACK, uvScale: 0.9 },
      // pan, nosed down at the front
      { geo: UNIT_BOX, m: mat(0, 0.440, 0.055, 0.05, 0, 0, 0.455, 0.065, 0.40), color: PAN, uvScale: 0.9 },
      // arms
      { geo: UNIT_BOX, m: mat(0.245, 0.545, -0.02, 0, 0, 0, 0.045, 0.10, 0.34), color: [0.74, 0.74, 0.75] },
      { geo: UNIT_BOX, m: mat(-0.245, 0.545, -0.02, 0, 0, 0, 0.045, 0.10, 0.34), color: [0.74, 0.74, 0.75] },
      // pedestal, on a foot plate
      { geo: UNIT_BOX, m: mat(0, 0.215, -0.055, 0, 0, 0, 0.13, 0.43, 0.10), color: FRAME },
    ]
    : [
      { geo: UNIT_BOX, m: mat(0, 0.700, -0.150, TILT, 0, 0, 0.455, 0.44, 0.055), color: BACK, uvScale: 0.9 },
      { geo: UNIT_BOX, m: mat(0, 0.442, 0.055, 0.05, 0, 0, 0.455, 0.060, 0.40), color: PAN, uvScale: 0.9 },
      { geo: UNIT_BOX, m: mat(0, 0.215, -0.055, 0, 0, 0, 0.14, 0.43, 0.10), color: FRAME },
    ];
  return parts(list, 'seat');
}

