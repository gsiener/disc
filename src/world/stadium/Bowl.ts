/** 8×12 atlas: cells 0..31 section plates "101"…"132", 32..95 row numbers. */
function bakeSignAtlas(): THREE.CanvasTexture {
  return canvasTexture(1024, 1024, (c, W, H) => {
    c.clearRect(0, 0, W, H);
    const cw = W / 8, ch = H / 12;
    c.textAlign = 'center';
    c.textBaseline = 'middle';
    for (let cell = 0; cell < 96; cell++) {
      const cx = (cell % 8) * cw, cy = Math.floor(cell / 8) * ch;
      if (cell < 32) {
        c.fillStyle = '#0d1c2c';
        c.fillRect(cx + 6, cy + 10, cw - 12, ch - 20);
        c.strokeStyle = '#d9a441';
        c.lineWidth = 3;
        c.strokeRect(cx + 6, cy + 10, cw - 12, ch - 20);
        c.fillStyle = '#f2f5f7';
        c.font = '700 42px "Helvetica Neue", Helvetica, Arial, sans-serif';
        c.fillText(String(101 + cell), cx + cw / 2, cy + ch / 2 + 6);
        c.font = '600 14px "Helvetica Neue", Helvetica, Arial, sans-serif';
        c.fillStyle = '#9fb4c6';
        c.fillText('SECTION', cx + cw / 2, cy + 24);
      } else {
        c.fillStyle = '#efe9d8';
        c.font = '800 44px "Helvetica Neue", Helvetica, Arial, sans-serif';
        c.fillText(String(cell - 31), cx + cw / 2, cy + ch / 2);
      }
    }
  }, { name: 'sign-atlas', anisotropy: 8 });
}
